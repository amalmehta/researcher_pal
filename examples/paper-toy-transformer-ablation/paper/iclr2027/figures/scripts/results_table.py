"""Write generated/tables/results.tex: mean [min, max] over seeds, best value per column in bold."""
import statistics

import data

rows = data.runs()
FLAGS = {"no_ramp_capped": ("capped", "yes"), "baseline": ("yes", "yes"), "no_scaling": ("yes", "no"), "no_warmup": ("no", "yes"), "no_warmup_no_scaling": ("no", "no")}

cells = {}
for config, _ in data.CONFIGS:
    rs = rows[config]
    acc = [100 * r["accuracy"] for r in rs]
    align = [100 * r["alignment"] for r in rs]
    loss = [r["final_loss"] for r in rs]
    cells[config] = {
        "acc": ("%.1f" % statistics.mean(acc), "[%.1f, %.1f]" % (min(acc), max(acc))),
        "align": ("%.1f" % statistics.mean(align), "[%.1f, %.1f]" % (min(align), max(align))),
        "loss": ("%.2f" % statistics.mean(loss), "[%.2f, %.2f]" % (min(loss), max(loss))),
    }

# Best = highest accuracy/alignment, lowest loss, compared at the printed precision (ties are all bold).
best = {
    "acc": max(float(c["acc"][0]) for c in cells.values()),
    "align": max(float(c["align"][0]) for c in cells.values()),
    "loss": min(float(c["loss"][0]) for c in cells.values()),
}


def cell(config, key):
    mean, spread = cells[config][key]
    shown = "\\textbf{%s}" % mean if float(mean) == best[key] else mean
    return "%s {\\scriptsize %s}" % (shown, spread)


lines = [
    "% Generated by figures/scripts/results_table.py. Do not edit by hand.",
    "\\begin{tabular}{lccccc}",
    "\\toprule",
    "Configuration & Warmup & Scaling & Accuracy (\\%) & Alignment (\\%) & Final loss \\\\",
    "\\midrule",
]
for config, label in data.CONFIGS:
    warm, scale = FLAGS[config]
    lines.append("%s & %s & %s & %s & %s & %s \\\\" % (label, warm, scale, cell(config, "acc"), cell(config, "align"), cell(config, "loss")))
lines += ["\\bottomrule", "\\end{tabular}", ""]
out = data.VENUE_DIR / "generated" / "tables" / "results.tex"
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text("\n".join(lines))
print("wrote", out.name)
